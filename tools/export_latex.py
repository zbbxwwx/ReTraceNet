#!/usr/bin/env python
"""Export evaluation JSON fields as reproducible LaTeX macros."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--prefix", default="Main")
    return parser.parse_args()


def command_name(prefix: str, key: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", key)
    return prefix + "".join(word.capitalize() for word in words)


def main() -> None:
    args = parse_args()
    with Path(args.results).open("r", encoding="utf-8") as handle:
        payload = json.load(handle)
    lines = ["% Auto-generated by tools/export_latex.py; do not hand-edit."]
    raw_metrics = {"manipulated_causal_drop"}
    for key, value in sorted(payload["metrics"].items()):
        if value is None:
            rendered = "--"
        elif key in raw_metrics:
            rendered = f"{float(value):.3f}"
        else:
            rendered = f"{100 * float(value):.2f}"
        lines.append(f"\\newcommand{{\\{command_name(args.prefix, key)}}}{{{rendered}}}")
    lines.append("\\newcommand{\\ResultSummary}{The preregistered quantitative evaluation has been completed; see the tables for dataset-level results.}")
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines) - 1} macros to {output}")


if __name__ == "__main__":
    main()
